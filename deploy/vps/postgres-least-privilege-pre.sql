\set ON_ERROR_STOP on
BEGIN;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'deopt_runtime') THEN
    CREATE ROLE deopt_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'deopt_migrator') THEN
    CREATE ROLE deopt_migrator NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'deopt_backup') THEN
    CREATE ROLE deopt_backup NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
  END IF;
END $$;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO deopt_runtime, deopt_migrator, deopt_backup;
GRANT CREATE ON SCHEMA public TO deopt_migrator;
GRANT SELECT, INSERT, UPDATE, DELETE ON _sqlx_migrations TO deopt_migrator;
COMMIT;
