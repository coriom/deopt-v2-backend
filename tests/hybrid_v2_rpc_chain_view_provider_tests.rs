fn addr20_str(seed: u8) -> String {
    let mut s = String::from("0x");
    for _ in 0..20 {
        s.push_str(&format!("{:02x}", seed));
    }
    s
}

fn subkey_bytes32(seed: u8) -> String {
    let mut s = String::from("0x");
    for _ in 0..32 {
        s.push_str(&format!("{:02x}", seed));
    }
    s
}

