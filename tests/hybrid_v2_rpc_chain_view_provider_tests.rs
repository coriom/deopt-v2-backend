#[tokio::test]
async fn provider_allowlist_covers_expected_selectors() {
    let mock = MockRpcServer::start().await;
    let source = source_for(&mock);
    let manifest = manifest_for_test(84532, "0xhash-a");
    let provider = RpcChainViewProvider::new(source, manifest.clone()).expect("provider");
    let map = provider.allowed_selectors();
    let mut expected: HashMap<[u8; 20], HashSet<[u8; 4]>> = HashMap::new();
    for (addr_str, sel) in [
        (
            &manifest.module_addresses.subaccount_registry,
            SELECTOR_OWNER_OF,
        ),
        (
            &manifest.module_addresses.collateral_vault,
            SELECTOR_BALANCE_WITH_YIELD,
        ),
        (
            &manifest.module_addresses.recovery_finalizer,
            SELECTOR_GET_RECOVERY_STATE,
        ),
    ] {
        let mut bytes = [0u8; 20];
        let stripped = addr_str.trim_start_matches("0x");
        for i in 0..20 {
            bytes[i] = u8::from_str_radix(&stripped[i * 2..i * 2 + 2], 16).unwrap();
        }
        expected.entry(bytes).or_default().insert(sel);
    }
    for (target, sels) in &expected {
        let got = map.get(target).expect("expected target in allowlist");
        for sel in sels {
            assert!(got.contains(sel), "missing selector for target");
        }
    }
    // A random selector must not be present.
    for (_, sels) in map.iter() {
        assert!(!sels.contains(&[0x00, 0x00, 0x00, 0x01]));
    }
}

#[tokio::test]
async fn provider_recovery_state_variants_decode_symbolically() {
    // Prove each numeric recovery-state variant decodes to the symbol
    // the reducer uses for parity, so a divergence between projection
    // (`RECOVERY_ACTIVE`) and chain (uint8=2) is a match, not a drift.
    for (v, label) in [
        (0u8, "NORMAL"),
        (1, "RECOVERY_PENDING"),
        (2, "RECOVERY_ACTIVE"),
        (3, "CANCELLED"),
        (4, "RECOVERED"),
    ] {
        let mock = MockRpcServer::start().await;
        let source = source_for(&mock);
        let manifest = manifest_for_test(84532, "0xhash-rs");
        let provider = RpcChainViewProvider::new(source, manifest.clone()).expect("provider");
        let sk = subkey_bytes32(0x11);
        mock.set_eth_call_response(
            &manifest.module_addresses.subaccount_registry,
            SELECTOR_OWNER_OF,
            abi_encode_address(&addr20_str(0xaa)),
        );
        mock.set_eth_call_response(
            &manifest.module_addresses.recovery_finalizer,
            SELECTOR_GET_RECOVERY_STATE,
            abi_encode_uint8(v),
        );
        let tokens: BTreeMap<String, Vec<String>> = BTreeMap::new();
        provider
            .fetch_snapshot_at(v as u64 + 1, &[sk.clone()], &tokens)
            .await
            .expect("fetch");
        let snap = provider.snapshot_at(v as u64 + 1).unwrap();
        assert_eq!(snap.recovery_state.get(&sk).unwrap(), label);
        // Sanity: the reducer's parity label matches too.
        match v {
            0 => assert_eq!(RecoveryStateProjection::Normal.as_str(), label),
            1 => assert_eq!(RecoveryStateProjection::RecoveryPending.as_str(), label),
            2 => assert_eq!(RecoveryStateProjection::RecoveryActive.as_str(), label),
            3 => assert_eq!(RecoveryStateProjection::Cancelled.as_str(), label),
            4 => assert_eq!(RecoveryStateProjection::Recovered.as_str(), label),
            _ => {}
        }
    }
}
