//! `BACKEND-HYBRID-V2-CHAIN-VIEW-PROVIDER-AND-RECONCILIATION-TASK-V1`
//! — mock-RPC integration tests for `RpcChainViewProvider`.
//!
//! Every test spins up the local axum-based mock JSON-RPC and exercises
//! the production provider's public surface. The mock refuses every
//! write/sign/wallet method with HTTP 500, so any accidental prohibited
//! call is a hard test failure.
//!
//! Coverage summary:
//! - allowlist rejection: unlisted address, unlisted selector, short data
//! - fetch_snapshot_at happy path: owner + balance + recovery decode
//! - drift detection: balance divergence classified as
//!   ProjectionDrift by the reconciler
//! - manifest mismatch surfaces as ManifestMismatch
//! - provider unavailable (429 exhaustion) surfaces as
//!   PROVIDER_UNAVAILABLE via mark_unavailable
//! - malformed hex response bubbles as ChainSourceError::Malformed
//! - 429 recovery via retry budget
//! - 503 recovery via retry budget
//! - Base mainnet chain-id is refused by chain identity validation
//! - No prohibited method ever generated by the provider

