#[tokio::test]
async fn provider_unlisted_selector_never_hits_the_network() {
    let mock = MockRpcServer::start().await;
    let source = source_for(&mock);
    // Pass a manifest whose recovery_finalizer address is registered,
    // but attempt an eth_call with a garbage selector via the
    // low-level source method — proves the allowlist trips inside
    // the source before any network I/O.
    let manifest = manifest_for_test(84532, "0xhash-x");
    let provider = RpcChainViewProvider::new(source.clone(), manifest.clone()).expect("provider");
    let allowlist = provider.allowed_selectors().clone();

    let out = source
        .eth_call(
            &manifest.module_addresses.recovery_finalizer,
            &[0xde, 0xad, 0xbe, 0xef, 0x00, 0x00, 0x00, 0x00],
            BlockRef::Number(1),
            &allowlist,
        )
        .await;
    assert!(matches!(out, Err(ChainSourceError::Unsupported(_))));
    // The mock records no call because the source refused before
    // dispatching a request.
    let calls = mock.calls();
    assert!(!calls.iter().any(|c| c.method == "eth_call"));
}

