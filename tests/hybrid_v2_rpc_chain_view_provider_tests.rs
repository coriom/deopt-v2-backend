#[tokio::test]
async fn provider_fetch_snapshot_owner_balance_recovery_round_trip() {
    let mock = MockRpcServer::start().await;
    let source = source_for(&mock);
    let manifest = manifest_for_test(84532, "0xhash1");
    let provider = RpcChainViewProvider::new(source, manifest.clone()).expect("provider");

    let sk = subkey_bytes32(0x01);
    let owner = addr20_str(0xaa);
    let token = addr20_str(0xef);

    // Fixture: ownerOf → owner address, balance → 100, recovery → 0/NORMAL.
    mock.set_eth_call_response(
        &manifest.module_addresses.subaccount_registry,
        SELECTOR_OWNER_OF,
        abi_encode_address(&owner),
    );
    mock.set_eth_call_response(
        &manifest.module_addresses.collateral_vault,
        SELECTOR_BALANCE_WITH_YIELD,
        abi_encode_uint256_dec("100"),
    );
    mock.set_eth_call_response(
        &manifest.module_addresses.recovery_finalizer,
        SELECTOR_GET_RECOVERY_STATE,
        abi_encode_uint8(0),
    );

    let mut tokens: BTreeMap<String, Vec<String>> = BTreeMap::new();
    tokens.insert(sk.clone(), vec![token.clone()]);
    provider
        .fetch_snapshot_at(42, &[sk.clone()], &tokens)
        .await
        .expect("fetch");

    let snap = provider.snapshot_at(42).expect("cached snapshot");
    assert_eq!(snap.manifest_hash, "0xhash1");
    assert_eq!(snap.subaccount_owners.get(&sk).unwrap(), &owner);
    assert_eq!(snap.balances.get(&(sk.clone(), token)).unwrap(), "100");
    assert_eq!(snap.recovery_state.get(&sk).unwrap(), "NORMAL");
    assert!(mock.prohibited_calls().is_empty());
}

